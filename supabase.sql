-- รันใน Supabase > SQL Editor ครั้งเดียว

-- 1. ตารางบันทึกอาหาร
CREATE TABLE IF NOT EXISTS meal_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users NOT NULL,
  food_name TEXT NOT NULL,
  calories NUMERIC NOT NULL,
  date DATE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. ตารางบันทึกการออกกำลังกาย
CREATE TABLE IF NOT EXISTS exercise_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users NOT NULL,
  exercise_name TEXT NOT NULL,
  calories_burned NUMERIC NOT NULL,
  duration_mins NUMERIC NOT NULL,
  date DATE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. สิทธิ์ Role
GRANT ALL ON TABLE meal_logs TO anon, authenticated;
GRANT ALL ON TABLE exercise_logs TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- 4. เปิด Row Level Security
ALTER TABLE meal_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE exercise_logs ENABLE ROW LEVEL SECURITY;

-- 5. Policies: ผู้ใช้จัดการได้เฉพาะข้อมูลของตนเอง
DROP POLICY IF EXISTS "Meal logs policy" ON meal_logs;
CREATE POLICY "Meal logs policy" ON meal_logs FOR ALL
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Exercise logs policy" ON exercise_logs;
CREATE POLICY "Exercise logs policy" ON exercise_logs FOR ALL
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
